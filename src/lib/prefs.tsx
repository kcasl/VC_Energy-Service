export type TextKey = keyof (typeof TEXT)["ko"];

const INDUSTRY: Record<string, string> = {
  cafe: "Cafe",
  korean: "Korean food",
  chicken: "Chicken / snacks",
  pub: "Pub",
  cvs: "Convenience store",
  beauty: "Beauty",
  academy: "Academy",
  retail: "Apparel",
  gym: "Gym",
  pharmacy: "Pharmacy",
};

type Prefs = {
  lang: Lang;
  theme: Theme;
  setLang: (lang: Lang) => void;
  setTheme: (theme: Theme) => void;
  t: (key: TextKey) => string;
  industry: (id: string, name: string) => string;
  level: (level: 1 | 2 | 3 | 4 | 5) => string;
};

const Ctx = createContext<Prefs | null>(null);

export function PrefsProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem("cvi-lang") === "en" ? "en" : "ko"));
  const [theme, setTheme] = useState<Theme>(() => (localStorage.getItem("cvi-theme") === "dark" ? "dark" : "light"));

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    document.documentElement.lang = lang === "en" ? "en" : "ko";
    document.title = lang === "en" ? "Commercial vitality · KENTECH" : "상권 활력 · KENTECH";
    localStorage.setItem("cvi-lang", lang);
    localStorage.setItem("cvi-theme", theme);
  }, [lang, theme]);

  const value: Prefs = {
    lang,
    theme,
    setLang,
    setTheme,
    t: (key) => TEXT[lang][key],
    industry: (id, name) => (lang === "en" ? INDUSTRY[id] ?? name : name),
    level: (level) => TEXT[lang][`lv${level}` as TextKey],
  };
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function usePrefs() {
  const value = useContext(Ctx);
  if (!value) throw new Error("prefs");
  return value;
}
